CREATE VIEW dupont_by_year as
SELECT i.company,
--净利率=净利润/营业收入
      round(i.net_income_2025*1.0/a.revenue_2025*100,2) as net_margin_2025,
	  round(i.net_income_2024*1.0/a.revenue_2024*100,2) as net_margin_2024,
	  round(i.net_income_2023*1.0/a.revenue_2023*100,2) as net_margin_2023,
	  round(i.net_income_2022*1.0/a.revenue_2022*100,2) as net_margin_2022,
	  round(i.net_income_2021*1.0/a.revenue_2021*100,2) as net_margin_2021,
--资产周转率=营业收入/总资产 周转次数
	  round(a.revenue_2025*1.0/b.assets_2025,2) as turnover_2025,
	  round(a.revenue_2024*1.0/b.assets_2024,2) as turnover_2024,
	  round(a.revenue_2023*1.0/b.assets_2023,2) as turnover_2023,
	  round(a.revenue_2022*1.0/b.assets_2022,2) as turnover_2022,
	  round(a.revenue_2021*1.0/b.assets_2021,2) as turnover_2021,
--权益乘数=总资产/净资产
      round(b.assets_2025*1.0/b.equity_2025,2) as equity_multiplier_2025,
	  round(b.assets_2024*1.0/b.equity_2024,2) as equity_multiplier_2024,
	  round(b.assets_2023*1.0/b.equity_2023,2) as equity_multiplier_2023,
	  round(b.assets_2022*1.0/b.equity_2022,2) as equity_multiplier_2022,
	  round(b.assets_2021*1.0/b.equity_2021,2) as equity_multiplier_2021
FROM net_income_by_year i
JOIN revenue_by_year a on i.company	=a.company
JOIN ratio_base b on i.company =b.company
GROUP by i.company;
